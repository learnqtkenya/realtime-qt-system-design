#!/usr/bin/env python3
"""Requirement B across versions: the step-09 viewer and this one, reading each other's recordings
and talking to each other over the wire. Writes results/step-10/compat.md.

    python3 scripts/step10_compat.py <step-09 viewer>
"""

import json
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NEW = ROOT / "build/release/app/viewer"
OLD = Path(sys.argv[1])
RAW = ROOT / "results/step-10/raw"
REC = ROOT / "build/release/recordings/step-10"


def run(app, label, args, duration=10, warmup=2):
    out = RAW / f"compat-{label}.json"
    cmd = [str(app), "--bench", "--warmup", str(warmup), "--duration", str(duration), "--label", label, "--out", str(out),
           "--set", "cameras=0", *args]
    p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=warmup + duration + 40)
    r = json.loads(out.read_text()) if out.exists() else {}
    st = r.get("stages", {})
    secs = r.get("measuredSeconds", 1) or 1
    return {"exit": p.returncode, "stderr": [l for l in p.stdout.splitlines() if l.strip()][:5],
            "lidarPerS": round(st.get("uploaded", {}).get("n", 0) / secs, 1),
            "notes": st.get("notes_presented", {}).get("n"), "latencyP50": r.get("latencyMs", {}).get("p50"),
            "fps": round(r.get("fps", 0), 1)}


def pair(server_app, client_app, label, port):
    server = subprocess.Popen([str(server_app), "--set", f"serve={port}", "--set", "cameras=0", "--set", "layout=0",
                               "--events", "0", "--set", "annotateEvery=1"],
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    time.sleep(3)
    r = run(client_app, label, ["--no-sim", "--set", f"connect=127.0.0.1:{port}"])
    server.terminate()
    out, _ = server.communicate(timeout=30)
    r["serverStderr"] = [l for l in out.splitlines() if l.strip()][:5]
    return r


def main():
    REC.mkdir(parents=True, exist_ok=True)
    RAW.mkdir(parents=True, exist_ok=True)
    new_file = REC / "with-notes.qprec"
    results = {}
    results["make a recording with notes (new)"] = run(NEW, "record", ["--events", "0", "--set", "annotateEvery=1",
                                                                       "--set", "record=1", "--set", "recordStopAt=12",
                                                                       "--set", f"recordPath={new_file}"], duration=12)
    old_files = sorted((ROOT / "build/release/recordings/step-04").glob("*.qprec"))[:3]
    results["new viewer replays its recording"] = run(NEW, "new-reads-new", ["--set", f"replay={new_file}"])
    results["old viewer replays the new recording"] = run(OLD, "old-reads-new", ["--set", f"replay={new_file}"])
    for f in old_files:
        results[f"new viewer replays step-04 {f.name}"] = run(NEW, f"new-reads-{f.stem}", ["--set", f"replay={f}"])
    results["old client, new server (notes on)"] = pair(NEW, OLD, "old-client-new-server", 7411)
    results["new client, old server"] = pair(OLD, NEW, "new-client-old-server", 7412)
    results["new client, new server (notes on)"] = pair(NEW, NEW, "new-client-new-server", 7413)
    (RAW / "compat.json").write_text(json.dumps(results, indent=1))
    rows = ["| Case | Exit | Lidar frames/s shown | Notes shown | Latency p50 | stderr |", "|---|---|---|---|---|---|"]
    for k, r in results.items():
        rows.append(f"| {k} | {r['exit']} | {r['lidarPerS']} | {r['notes'] if r['notes'] is not None else '–'} | "
                    f"{r['latencyP50'] if r['latencyP50'] is not None else '–'} | "
                    f"{'; '.join(r['stderr'] + r.get('serverStderr', [])) or 'clean'} |")
    (ROOT / "results/step-10/compat.md").write_text(
        "# Step 10: notes across versions\n\n*Old* is the viewer at tag `step-09`, built from that tag; *new* is this one. "
        "Recordings are replayed for 10 s after 2 s; network cases run a client for 10 s against a server noting an "
        "object every second. *Notes shown* is counted by the new viewer only (the old one has no counter). "
        "Generated by `scripts/step10_compat.py`.\n\n" + "\n".join(rows) + "\n")
    print("\n".join(rows))


if __name__ == "__main__":
    main()
