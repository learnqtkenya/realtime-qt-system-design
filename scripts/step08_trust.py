#!/usr/bin/env python3
"""What a plugin of each kind can reach. Serves a page on 127.0.0.1:8765, runs the viewer with each
"curious" lab plugin, and writes results/step-08/trust.md with what each one reported.

    python3 scripts/step08_trust.py
"""

import http.server
import json
import subprocess
import tempfile
import threading
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "build/release/app/viewer"
OUT = ROOT / "results/step-08"

CASES = [
    ("Item plugin (viewer's QML engine)", {"layers": "curious-item"}),
    ("Script plugin, QML entry (own QML engine)", {"layers": "curious-script"}),
    ("Script plugin, JS module (own JS engine)", {"layers": "curious-js"}),
    ("Process plugin", {"layers": "curious-process"}),
    ("Process plugin in bwrap", {"layers": "curious-process", "sandbox": 1}),
]


def serve(directory):
    handler = lambda *a: http.server.SimpleHTTPRequestHandler(*a, directory=directory)  # noqa: E731
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 8765), handler)
    server.RequestHandlerClass.log_message = lambda *a: None
    threading.Thread(target=server.serve_forever, daemon=True).start()
    return server


def main():
    www = tempfile.mkdtemp()
    (Path(www) / "index.html").write_text("secret page\n")
    server = serve(www)
    sections = ["# Step 8: what a plugin can reach\n",
                "Each lab plugin tries the same things and reports what happened. A page is served on "
                "127.0.0.1:8765 for the network attempts (`index.html`, 12 bytes). "
                "Generated by `scripts/step08_trust.py`.\n"]
    for title, settings in CASES:
        with tempfile.TemporaryDirectory() as tmp:
            log = Path(tmp) / "layers.jsonl"
            report = Path(tmp) / "report.json"
            args = [str(APP), "--bench", "--warmup", "1", "--duration", "6", "--label", "trust", "--out", str(report),
                    "--objects", "50", "--set", "cameras=0", "--set", "labPlugins=1", "--set", f"layerLog={log}"]
            for k, v in settings.items():
                args += ["--set", f"{k}={v}"]
            proc = subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=60)
            lines = [l for l in proc.stdout.splitlines() if "curious" in l]
            if log.exists():
                for entry in map(json.loads, log.read_text().splitlines()):
                    if "curious" in entry.get("message", ""):
                        lines.append(entry["message"])
        sections.append(f"## {title}\n\n`{' '.join(f'--set {k}={v}' for k, v in settings.items())}`\n\n```\n"
                        + ("\n".join(lines) or "(nothing reported)") + "\n```\n")
    server.shutdown()
    (OUT / "trust.md").write_text("\n".join(sections))
    print(f"wrote {OUT / 'trust.md'}")


if __name__ == "__main__":
    main()
