#!/usr/bin/env python3
"""Step 4 tables from results/step-04/raw/*.json -> results/step-04/analysis.md.

Medians across repeats (-rN) where a configuration was run more than once.
"""

import json
import re
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "results/step-04/raw"


def load():
    reports = {}
    for p in sorted(RAW.glob("*.json")):
        reports[p.stem] = json.loads(p.read_text())
    return reports


def groups(reports, prefix):
    out = {}
    for label, r in reports.items():
        if not label.startswith(prefix):
            continue
        out.setdefault(re.sub(r"-r\d+$", "", label), []).append(r)
    return out


def med(runs, f):
    vals = [v for v in (f(r) for r in runs) if v is not None]
    return st.median(vals) if vals else None


def stage(r, name, key="p50"):
    s = r.get("stages", {}).get(name)
    return s.get(key) if s and s.get("n") else None


def metric(r, name, key="p50"):
    m = r.get(name, {})
    return m.get(key) if m and m.get("n") else None


def fmt(v, d=1):
    if v is None:
        return "–"
    if isinstance(v, str):
        return v
    return f"{v:,.{d}f}"


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(fmt(c) if not isinstance(c, str) else c for c in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def health(runs):
    """Anything that would make a run untrustworthy."""
    notes = []
    for r in runs:
        if r.get("stderrLines"):
            notes.append(f"{r['label']}: {len(r['stderrLines'])} stderr lines")
        if r.get("stalled") or r.get("aborted"):
            notes.append(f"{r['label']}: stalled/aborted")
        if r.get("attempts", 1) > 1:
            notes.append(f"{r['label']}: {r['attempts']} attempts")
    return notes


def main():
    reports = load()
    out = ["# Step 4 analysis\n",
           f"Generated by `scripts/step04_report.py` from `results/step-04/raw/` ({len(reports)} reports). "
           "Medians across repeats; n = runs.\n"]
    notes = health(reports.values())

    g = groups(reports, "sync-")
    if g:
        out.append("## Agreeing on now: latest frame against a shared clock\n")
        out.append("Nominal load, 3D view, four cameras (VA-API, forward). *lag* = simulated lidar processing; "
                   "*clock D* = every stream shown at now − D. Skew = camera time − lidar time on screen. "
                   "*Late*: how long after its due time each lidar frame was shown (0 when the clock waits for it).\n")
        rows = []
        for name in ("sync-lag0-latest", "sync-lag0-clock100", "sync-lag150-latest", "sync-lag150-clock200",
                     "sync-lag150-clock120"):
            runs = g.get(name)
            if not runs:
                continue

            rows.append([name.removeprefix("sync-"), str(len(runs)),
                         med(runs, lambda r: metric(r, "cameraAbsSkewMs")),
                         med(runs, lambda r: metric(r, "cameraAbsSkewMs", "p99")),
                         med(runs, lambda r: metric(r, "latencyMs")),
                         med(runs, lambda r: metric(r, "latencyMs", "p99")),
                         med(runs, lambda r: metric(r, "cameraLatencyMs")),
                         med(runs, lambda r: stage(r, "live_late_ms", "p50")),
                         med(runs, lambda r: stage(r, "live_late_ms", "p99")),
                         med(runs, lambda r: r["fps"]),
                         med(runs, lambda r: r["eventLoopLagMs"]["p99"]),
                         med(runs, lambda r: r["processCpuPercent"]["mean"])])
        out.append(table(["config", "n", "\\|skew\\| p50", "\\|skew\\| p99", "lidar lat p50", "lidar lat p99",
                          "camera lat p50", "late p50 ms", "late p99 ms", "fps", "GUI lag p99", "CPU %"], rows))

    g = groups(reports, "history-")
    if g:
        out.append("## Keeping the past in memory\n")
        out.append("60 s runs, nominal load, cameras off. RSS sampled every second. *shared-pool*: the simulator "
                   "reuses four clouds per sensor (as in steps 1–3); *fresh*: every frame is its own allocation.\n")
        rows = []
        for name in ("history-shared-pool-none", "history-fresh-none", "history-fresh-shared-1000",
                     "history-fresh-int16-1000", "history-shared-pool-shared-1000"):
            runs = g.get(name)
            if not runs:
                continue
            r = runs[0]
            series = r.get("rssSeriesMb") or []
            rows.append([name.removeprefix("history-"), fmt(series[9] if len(series) > 9 else None, 0),
                         fmt(series[29] if len(series) > 29 else None, 0), fmt(series[-1] if series else None, 0),
                         r["processCpuPercent"]["mean"], stage(r, "history_add_ms"), stage(r, "history_add_ms", "p99"),
                         r["eventLoopLagMs"]["p99"], r["fps"]])
        out.append(table(["config", "RSS at 10 s", "RSS at 30 s", "RSS at end", "CPU %", "add p50 ms",
                          "add p99 ms", "GUI lag p99", "fps"], rows))

    g = groups(reports, "record-")
    if g:
        out.append("## Recording to disk\n")
        out.append("Recorded from the start for about 22 s, cameras off unless named. Rates are file bytes over the "
                   "recorded time; writer CPU is encode + compress + write time on the writer thread; *stop* is "
                   "draining the queue, writing the index and syncing the file to disk.\n")
        rows = []
        for name in sorted(g):
            r = g[name][0]
            s = lambda k: stage(r, k, "max")  # noqa: E731  (totals are single samples)
            file_mb, raw_mb = s("record_file_mb"), s("record_raw_mb")
            secs = s("record_seconds") or 26.5
            writer_ms = sum(v or 0 for v in (s("record_encode_ms_total"), s("record_compress_ms_total"),
                                             s("record_write_ms_total")))
            rows.append([name.removeprefix("record-"), file_mb,
                         file_mb / secs if file_mb else None,
                         raw_mb / file_mb if file_mb and raw_mb else None,
                         s("record_dropped"), s("record_queue_max_mb"), s("record_at_risk_max_mb"),
                         writer_ms / secs / 10 if writer_ms else None,
                         stage(r, "record_chunk_write_ms", "p99"),
                         s("record_out_of_order"), s("record_max_disorder_ms"), s("record_stop_ms"),
                         r["fps"], r["eventLoopLagMs"]["p99"], r["processCpuPercent"]["mean"]])
        out.append(table(["config", "file MB", "MB/s", "compression", "dropped", "queue max MB",
                          "at risk max MB", "writer % of a core", "chunk write p99 ms", "out of order",
                          "max disorder ms", "stop ms", "fps", "GUI lag p99", "CPU %"], rows))

    g = {**groups(reports, "replay-"), **groups(reports, "seek-"), **groups(reports, "scrub-")}
    if g:
        out.append("## Replay, seek and scrub\n")
        out.append("Nominal load, 3D view, four cameras. In replay, latency is measured from when a sample was "
                   "due (or, paused, from the seek) to the photon. *Late* is presenter lateness (actual − due). "
                   "Skew is shown for playing runs only: paused, both stamps are seek times, and for the ~90 ms a "
                   "camera seek takes the screen pairs a new lidar frame with the previous seek's camera frame. "
                   "*Cam seek worst error*: the shown camera frame's capture time minus the playhead, worst case "
                   "(one frame period, −33 ms, is exact).\n")
        rows = []
        for name in sorted(g):
            runs = g[name]
            if name == "replay-source":
                continue
            rows.append([name, str(len(runs)),
                         med(runs, lambda r: stage(r, "present_late_ms", "p50")),
                         med(runs, lambda r: stage(r, "present_late_ms", "p99")),
                         med(runs, lambda r: stage(r, "seek_ms", "p50")),
                         med(runs, lambda r: stage(r, "seek_ms", "p99")),
                         med(runs, lambda r: metric(r, "latencyMs")),
                         med(runs, lambda r: metric(r, "latencyMs", "p99")),
                         med(runs, lambda r: stage(r, "camera_seek_ms", "p50")),
                         med(runs, lambda r: stage(r, "camera_seek_ms", "p99")),
                         med(runs, lambda r: metric(r, "cameraLatencyMs")),
                         med(runs, lambda r: metric(r, "cameraAbsSkewMs")) if name.startswith("replay") else "–",
                         med(runs, lambda r: stage(r, "camera_seek_error_ms", "min")),
                         med(runs, lambda r: metric(r, "inputLatencyMs", "p99")),
                         med(runs, lambda r: r["fps"]),
                         med(runs, lambda r: r["eventLoopLagMs"]["p99"]),
                         med(runs, lambda r: r["processCpuPercent"]["mean"]),
                         med(runs, lambda r: r["rssMb"]["max"])])
        out.append(table(["run", "n", "late p50", "late p99", "seek p50", "seek p99", "lidar lat p50",
                          "lidar lat p99", "cam seek p50", "cam seek p99", "cam lat p50", "\\|skew\\| p50",
                          "cam seek worst error ms", "input p99", "fps", "GUI lag p99", "CPU %", "RSS max"], rows))

    g = groups(reports, "soak-")
    if g:
        out.append("## Soaks\n")
        for name, runs in sorted(g.items()):
            r = runs[0]
            series = r.get("rssSeriesMb") or []
            every30 = [round(series[i]) for i in range(29, len(series), 30)]
            out.append(f"- **{name}**: RSS every 30 s {every30}; fps {r['fps']:.1f}; GUI lag p99 "
                       f"{r['eventLoopLagMs']['p99']:.1f} ms; CPU {r['processCpuPercent']['mean']:.0f}%"
                       + (f"; recorded {stage(r, 'record_file_mb', 'max'):.0f} MB, dropped "
                          f"{stage(r, 'record_dropped', 'max'):.0f}" if stage(r, "record_file_mb", "max") else "")
                       + "\n")

    out.append("## Run health\n")
    out.append("\n".join(f"- {n}" for n in notes) + "\n" if notes else "Every run: no stderr, no stall, first attempt.\n")
    (ROOT / "results/step-04/analysis.md").write_text("\n".join(out))
    print((ROOT / "results/step-04/analysis.md").read_text())


if __name__ == "__main__":
    main()
