#!/usr/bin/env python3
"""Step 6 tables from results/step-06/raw/*.json -> results/step-06/analysis.md."""

import json
import re
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "results/step-06/raw"


def groups(prefix):
    out = {}
    for p in sorted(RAW.glob(f"{prefix}*.json")):
        out.setdefault(re.sub(r"-r\d+$", "", p.stem), []).append(json.loads(p.read_text()))
    return out


def stage(r, name, key="p50"):
    s = r.get("stages", {}).get(name)
    return s.get(key) if s and s.get("n") else None


def med(vals):
    vals = [v for v in vals if v is not None]
    return st.median(vals) if vals else None


def fmt(v, d=0):
    return "–" if v is None else (v if isinstance(v, str) else f"{v:,.{d}f}")


def table(header, rows):
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
                     + ["| " + " | ".join(fmt(c) if not isinstance(c, float) or True else c for c in row) + " |"
                        for row in rows]) + "\n"


def unexpected(r):
    return {k.removeprefix("unexpected_"): v["n"] for k, v in r.get("stages", {}).items() if k.startswith("unexpected_")}


def main():
    out = ["# Step 6 analysis\n", "Generated by `scripts/step06_report.py`.\n"]
    g = groups("detect-")
    if g:
        out.append("## Detection and recovery\n\nNominal load (4 × 150k points at 10 Hz, 200 objects, 200 events/s, four "
                   "cameras). Fault injected at 5 s, cleared at 10 s. *Detect*: injection to the stream's first "
                   "non-ok status; *recover*: clearing to ok (the 300 ms hold included). Three runs; all values shown. "
                   "*Alarms on other streams*: status changes on streams with no fault (a fault is attributed to its stream until the stream is ok again after clearing).\n")
        rows = []
        for name, runs in g.items():
            det = [next((v["max"] for k, v in r["stages"].items() if re.fullmatch(r"detect_[a-z0-9]+_ms", k)), None)
                   for r in runs]
            rec = [stage(r, "recover_ms", "max") for r in runs]
            others = {}
            for r in runs:
                for k, v in unexpected(r).items():
                    others[k] = others.get(k, 0) + v
            per_status = {}
            for r in runs:
                for k, v in r["stages"].items():
                    m = re.match(r"detect_[a-z0-9]+_([a-z]+)_ms$", k)
                    if m:
                        per_status.setdefault(m.group(1), []).append(v["max"])
            first_each = ", ".join(f"{st_} {med(v):.0f}" for st_, v in sorted(per_status.items(), key=lambda kv: med(kv[1])))
            rows.append([name.removeprefix("detect-"), " / ".join(fmt(d) for d in det), first_each,
                         " / ".join(fmt(d) for d in rec),
                         ", ".join(f"{k} ×{v}" for k, v in sorted(others.items())) or "none",
                         fmt(med([r["fps"] for r in runs]), 1), fmt(med([r["eventLoopLagMs"]["p99"] for r in runs]), 1),
                         fmt(med([r["frameMs"]["p99"] for r in runs]), 1)])
        out.append(table(["fault", "detect ms (3 runs)", "first entry to each status, median ms", "recover ms",
                          "alarms on other streams (3 runs)", "fps", "GUI lag p99", "frame p99"],
                         rows))
    g = groups("validate-")
    if g:
        out.append("## Validation cost\n\nCameras off. *validate* is the check of every lidar frame on the simulator "
                   "thread.\n")
        rows = [[name.removeprefix("validate-"), str(len(runs)), fmt(med([stage(r, "validate_ms") for r in runs]), 3),
                 fmt(med([stage(r, "validate_ms", "p99") for r in runs]), 3),
                 fmt(med([r["processCpuPercent"]["mean"] for r in runs]), 1),
                 fmt(med([r["eventLoopLagMs"]["p99"] for r in runs]), 1)] for name, runs in g.items()]
        out.append(table(["config", "n", "validate p50 ms", "p99 ms", "process CPU %", "GUI lag p99"], rows))
    g = groups("order-")
    if g:
        out.append("## Out-of-order arrivals\n\nLidar 2 with ±100 ms jitter from 4 s; *keep0*: the live view shows "
                   "whatever arrived last, *keep1*: never older than what is shown.\n")
        rows = [[name.removeprefix("order-"), str(len(runs)),
                 fmt(med([r["stages"].get("lidar_shown_backwards", {}).get("n", 0) / r["measuredSeconds"] for r in runs]), 1),
                 fmt(med([r["stages"].get("lidar_older_not_shown", {}).get("n", 0) / r["measuredSeconds"] for r in runs]), 1),
                 fmt(med([next((v["max"] for k, v in r["stages"].items() if re.fullmatch(r"detect_[a-z0-9]+_ms", k)), None)
                          for r in runs]))]
                for name, runs in g.items()]
        out.append(table(["config", "n", "frames shown backwards /s", "older frames not shown /s", "detect ms"], rows))
    for prefix, title in (("novalidate-", "Corruption without validation"), ("jitter-record", "Jitter while recording"),
                          ("quiet-", "False alarms (no faults)")):
        g = groups(prefix)
        if not g:
            continue
        out.append(f"## {title}\n")
        for name, runs in g.items():
            r = runs[0]
            extra = ""
            if stage(r, "record_out_of_order", "max") is not None:
                extra = (f"; recording: {stage(r, 'record_out_of_order', 'max'):.0f} records out of order, worst "
                         f"{stage(r, 'record_max_disorder_ms', 'max'):.0f} ms")
            det = {k: v["max"] for k, v in r["stages"].items() if k.startswith("detect_")}
            out.append(f"- **{name}** ({r['measuredSeconds']:.0f} s): unexpected status changes "
                       f"{unexpected(r) or 'none'}; detections {det or 'none'}; fps {r['fps']:.1f}; GUI lag p99 "
                       f"{r['eventLoopLagMs']['p99']:.1f} ms; CPU {r['processCpuPercent']['mean']:.0f}%{extra}\n")
    health = []
    for p in sorted(RAW.glob("*.json")):
        r = json.loads(p.read_text())
        if r.get("stderrLines") or r.get("stalled") or r.get("aborted") or r.get("attempts", 1) > 1:
            health.append(f"- {p.stem}: stderr {r.get('stderrLines', [])[:1]}, stalled {r.get('stalled')}, "
                          f"attempts {r.get('attempts', 1)}")
    out.append("## Run health\n\n" + ("\n".join(health) if health else "Every run: no stderr, no stall, first attempt.")
               + "\n")
    (ROOT / "results/step-06/analysis.md").write_text("\n".join(out))
    print((ROOT / "results/step-06/analysis.md").read_text())


if __name__ == "__main__":
    main()
