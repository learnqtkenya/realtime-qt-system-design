#!/usr/bin/env python3
"""Step 5 tables from results/step-05/raw/*.json -> results/step-05/analysis.md (medians of repeats)."""

import json
import re
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "results/step-05/raw"


def groups(prefix):
    out = {}
    for p in sorted(RAW.glob(f"{prefix}*.json")):
        out.setdefault(re.sub(r"-r\d+$", "", p.stem), []).append(json.loads(p.read_text()))
    return out


def med(runs, f):
    vals = [v for v in (f(r) for r in runs) if v is not None]
    return st.median(vals) if vals else None


def stage(r, name, key="p50"):
    s = r.get("stages", {}).get(name)
    return s.get(key) if s and s.get("n") else None


def rate(r, name):
    s = r.get("stages", {}).get(name)
    return s["n"] / r["measuredSeconds"] if s and r["measuredSeconds"] > 0 else 0.0


def gui_ms_per_s(r, name):
    s = r.get("stages", {}).get(name)
    return s["n"] * s["mean"] / r["measuredSeconds"] if s and s.get("n") else 0.0


def fmt(v, d=1):
    if v is None:
        return "–"
    if isinstance(v, str):
        return v
    return f"{v:,.{d}f}"


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(fmt(c) for c in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


COMMON = ["fps", "frame p99", "GUI lag p99", "GUI CPU %", "proc CPU %"]


def common(runs):
    return [med(runs, lambda r: r["fps"]), med(runs, lambda r: r["frameMs"]["p99"]),
            med(runs, lambda r: r["eventLoopLagMs"]["p99"]), med(runs, lambda r: r["guiCpuPercent"]["mean"]),
            med(runs, lambda r: r["processCpuPercent"]["mean"])]


def main():
    out = ["# Step 5 analysis\n", "Generated by `scripts/step05_report.py`. Medians across repeats (n).\n"]
    health = []
    for p in sorted(RAW.glob("*.json")):
        r = json.loads(p.read_text())
        if r.get("stderrLines") or r.get("stalled") or r.get("aborted") or r.get("attempts", 1) > 1:
            health.append(f"- {p.stem}: stderr {len(r.get('stderrLines', []))}, stalled {r.get('stalled')}, "
                          f"aborted {bool(r.get('aborted'))}, attempts {r.get('attempts', 1)}")

    def section(title, intro, prefix, extra_header, extra):
        g = groups(prefix)
        if not g:
            return
        rows = [[name, str(len(runs)), *extra(runs), *common(runs)] for name, runs in g.items()]
        out.append(f"## {title}\n\n{intro}\n")
        out.append(table(["run", "n", *extra_header, *COMMON], rows))

    track_cols = ["model update p50 ms", "p99 ms", "model ms/s", "rows created/s"]

    def track_extra(runs):
        return [med(runs, lambda r: stage(r, "tracks_rebuild_ms")), med(runs, lambda r: stage(r, "tracks_rebuild_ms", "p99")),
                med(runs, lambda r: gui_ms_per_s(r, "tracks_rebuild_ms")), med(runs, lambda r: rate(r, "table_row_created"))]

    section("Objects", "Top-down RHI view and the data panel, 10 Hz track updates, 50 events/s, cameras off. "
            "*Model update*: the model and the table's sort/filter proxy, synchronous, on the GUI thread "
            "(delegate rebuilding happens later, in the views).", "objects-", track_cols, track_extra)
    section("Objects without the panel", "As above, data panel hidden: what the top-down view's own track "
            "delegates cost.", "panel-off-", track_cols, track_extra)
    section("Sorting", "2,000 objects; the table sorted by id (never changes) or by speed (changes every update).",
            "sort-", track_cols, track_extra)

    def event_extra(runs):
        return [med(runs, lambda r: stage(r, "event_reset_ms")), med(runs, lambda r: stage(r, "event_reset_ms", "p99")),
                med(runs, lambda r: gui_ms_per_s(r, "event_reset_ms")), med(runs, lambda r: rate(r, "log_row_created")),
                med(runs, lambda r: r["rssMb"]["max"]), med(runs, lambda r: r["rssGrowthMbPerMinute"])]

    ev_cols = ["batch p50 ms", "p99 ms", "model ms/s", "log rows created/s", "RSS max", "RSS MB/min"]
    section("Events", "50 objects; 20 batches per second; reset keeps every event, diff keeps the newest 10,000.",
            "events-", ev_cols, event_extra)
    section("Event soak", "2,000 events/s for 3 minutes.", "eventsoak-", ev_cols, event_extra)
    section("Search", "2,000 events/s; the search text toggles between \"late\" and empty every 0.5 s. "
            "`search-reset`/`search-diff` (round 1): proxy filter, no delegate reuse. `search-proxy`/`search-index` "
            "(round 3): diff updates, reuse on, filter as a proxy or as an index model.",
            "search-", ["filter p50 ms", "filter p99 ms", *ev_cols],
            lambda runs: [med(runs, lambda r: stage(r, "event_filter_ms")),
                          med(runs, lambda r: stage(r, "event_filter_ms", "p99")), *event_extra(runs)])
    section("3D boxes", "3D orbit view and the data panel.", "orbit-",
            [*track_cols, "instancing p50 ms", "instancing p99 ms"],
            lambda runs: [*track_extra(runs), med(runs, lambda r: stage(r, "instancing_build_ms")),
                          med(runs, lambda r: stage(r, "instancing_build_ms", "p99"))])
    section("Top-down overlay as one node", "Top-down RHI view, diff updates; boxes and labels drawn by one "
            "scene graph subtree (*node*) or a QML item per object (*items*). Labels for every object up to 200, "
            "then only the selected one. *Overlay sync*: building the subtree on the render thread (GUI blocked).",
            "overlay-", [*track_cols, "overlay sync p50 ms", "p99 ms"],
            lambda runs: [*track_extra(runs), med(runs, lambda r: stage(r, "overlay_sync_ms")),
                          med(runs, lambda r: stage(r, "overlay_sync_ms", "p99"))])
    section("Sorting, isolated", "3D view with instanced boxes (no per-object QML items), 2,000 objects, diff updates; "
            "the table sorted by id or by speed.", "sort3d-", track_cols, track_extra)
    section("Event soak, history off", "2,000 events/s for 3 minutes, history budget 0, so RSS is the event log's.",
            "eventsoak-nohistory-", ev_cols, event_extra)
    section("Everything at once", "2,000 objects, 2,000 events/s, four cameras, diff updates, node overlay, instanced "
            "boxes, 30 s.", "all-", [*track_cols, *ev_cols[:2]],
            lambda runs: [*track_extra(runs), *event_extra(runs)[:2]])
    section("Delegate reuse", "Event log at 2,000 events/s, diff updates, list views with `reuseItems` off (0) or on (1).",
            "reuse-", ["log rows created/s", "log rows reused/s", "batch p50 ms"],
            lambda runs: [med(runs, lambda r: rate(r, "log_row_created")), med(runs, lambda r: rate(r, "log_row_reused")),
                          med(runs, lambda r: stage(r, "event_reset_ms"))])
    out.append("## Run health\n\n" + ("\n".join(health) if health else "Every run: no stderr, no stall, first attempt.") + "\n")
    (ROOT / "results/step-05/analysis.md").write_text("\n".join(out))
    print((ROOT / "results/step-05/analysis.md").read_text())


if __name__ == "__main__":
    main()
