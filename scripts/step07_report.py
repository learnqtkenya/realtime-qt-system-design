#!/usr/bin/env python3
"""Step 7 tables from results/step-07/raw/*.json -> results/step-07/analysis.md (medians of repeats)."""

import json
import re
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "results/step-07/raw"


def load():
    runs = {}
    for p in sorted(RAW.glob("*.json")):
        m = re.match(r"(.+?)-r(\d+)-(.+)$", p.stem)
        if m:
            runs.setdefault((m.group(1), m.group(3)), []).append(json.loads(p.read_text()))
    return runs


def med(vals):
    vals = [v for v in vals if v is not None]
    return st.median(vals) if vals else None


def stage(r, name, key="p50"):
    s = r.get("stages", {}).get(name)
    return s.get(key) if s and s.get("n") else None


def fmt(v, d=1):
    return "–" if v is None else (v if isinstance(v, str) else f"{v:,.{d}f}")


def row(config, role, rs):
    lat = lambda k: med([r["latencyMs"][k] if r["latencyMs"]["n"] else None for r in rs])  # noqa: E731
    series = [r.get("rssSeriesMb") or [] for r in rs]
    return [config, role, str(len(rs)), fmt(lat("p50")), fmt(lat("p99")),
            fmt(med([r["latencyMs"]["n"] / r["measuredSeconds"] for r in rs])),
            fmt(med([stage(r, "server_client_mbps") or stage(r, "client_mbps") for r in rs])),
            fmt(med([stage(r, "server_encode_ms") for r in rs]), 2),
            fmt(med([stage(r, "server_backlog_mb", "max") for r in rs])),
            fmt(med([s[-1] if s else None for s in series]), 0),
            fmt(med([r["processCpuPercent"]["mean"] for r in rs]), 0),
            fmt(med([r["eventLoopLagMs"]["p99"] for r in rs])),
            str(sum(len(r.get("stderrLines", [])) for r in rs))]


def main():
    runs = load()
    head = ["config", "process", "n", "latency p50 ms", "p99 ms", "lidar updates/s", "MB/s", "encode ms/frame",
            "backlog max MB", "RSS at end, MB (1 GB history included)", "CPU %", "GUI lag p99", "stderr"]
    out = ["# Step 7 analysis\n", "Generated by `scripts/step07_report.py`. Nominal load (4 × 150k points at 10 Hz, 200 "
           "objects, 200 events/s), cameras off, all processes on one machine. Latency: capture (simulator, server "
           "process) to photon in that process (one monotonic clock). Medians of repeats.\n",
           "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    order = ["encode-zstd0", "encode-zstd1", "clients1", "clients2", "clients4", "slow-all", "slow-latest",
             "buffers-small", "restart"]
    for config in order:
        roles = sorted({k[1] for k in runs if k[0] == config}, key=lambda r: (r != "server", r))
        for role in roles:
            out.append("| " + " | ".join(row(config, role, runs[(config, role)])) + " |")
    alarms = []
    for (config, role), rs in sorted(runs.items()):
        if role == "server":
            continue
        a = {}
        for r in rs:
            for k, v in r["stages"].items():
                if k.startswith("unexpected_"):
                    kind = k.rsplit("_", 1)[1]
                    a[kind] = a.get(kind, 0) + v["n"]
        conns = sum(r["stages"].get("client_connected", {}).get("n", 0) for r in rs)
        if a or conns:
            alarms.append(f"- **{config} / {role}** ({len(rs)} runs): health alarms {a or 'none'}; "
                          f"connections inside the measured window {conns}")
    out.append("\n## Client health\n\n" + "\n".join(alarms) + "\n")
    (ROOT / "results/step-07/analysis.md").write_text("\n".join(out) + "\n")
    print((ROOT / "results/step-07/analysis.md").read_text())


if __name__ == "__main__":
    main()
